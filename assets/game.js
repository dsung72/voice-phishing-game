    function preferredKoreanVoice() {
      if(!("speechSynthesis" in window)) return cachedKoreanVoice;
      const korean=window.speechSynthesis.getVoices().filter(voice=>/^ko(?:-|_)/i.test(voice.lang));
      const femalePattern=/SunHi|Heami|Yuna|Sora|YuJin|여성|선희|혜미|유진/i;
      const voiceScore=voice=>{
        const name=voice.name || "";
        let score=0;
        if(/Hyunsu|InJoon|BongJin|Male|남성|현수|인준|봉진/i.test(name)) score+=80;
        if(/Natural|Online|Neural|자연/i.test(name)) score+=45;
        if(/Microsoft|Google/i.test(name)) score+=12;
        if(voice.default) score+=3;
        if(femalePattern.test(name)) score-=120;
        return score;
      };
      const selected=[...korean].sort((a,b)=>voiceScore(b)-voiceScore(a))[0] || null;
      if(selected) cachedKoreanVoice=selected;
      return cachedKoreanVoice;
    }
