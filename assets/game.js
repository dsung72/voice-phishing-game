    function choose(choiceIndex, timedOut=false) {
      if(state.inputLocked) return;
      state.inputLocked=true; stopTimer(); stopCallTimer(); stopVoicePlayback(); clearEasyHint();
      const s=state.queue[state.index];
      const choice=timedOut?null:s.choices[choiceIndex];
      const correct=!!choice?.correct;
      window.GameAudio?.effect(correct ? "correct" : timedOut ? "timeout" : "wrong");
      trackGameEvent("scenario_answer",{
        game_mode:analyticsLevelName(),
        fraud_type:s.type,
        question_number:state.index+1,
        correct,
        timed_out:timedOut
      });
      if(correct){ state.correct++; navigator.vibrate?.(35); }
      else { state.wrongs.push({type:s.type,title:s.title,lesson:s.lesson}); navigator.vibrate?.([60,40,60]); triggerWrongShake(); }
      if(correct) showFeedback({s,choice,correct,timedOut});
      else setTimeout(()=>{ if(state.screen==="game") showFeedback({s,choice,correct,timedOut}); },260);
    }

