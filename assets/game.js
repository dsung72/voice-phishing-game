    function playVoiceScenario() {
      const panel=document.querySelector(".voice-audio-panel");
      if(!panel || state.mode!=="voice-audio") return;
      if(panel.classList.contains("speaking")) { stopVoicePlayback(); return; }
      if(!("speechSynthesis" in window) || !("SpeechSynthesisUtterance" in window)) {
        updateVoiceAudioPanel(false,"이 브라우저에서는 음성 재생을 지원하지 않아요.");
        toast("Chrome·Edge·Safari 최신 버전에서 음성 체험을 이용해 주세요.");
        return;
      }
      const s=state.queue[state.index];
      if(!s) return;
      const token=++voicePlaybackToken;
      if(voicePauseTimer){ clearTimeout(voicePauseTimer); voicePauseTimer=null; }
      window.speechSynthesis.cancel();
      const segments=voiceScriptForScenario(s);
      const voice=preferredKoreanVoice();
      let segmentIndex=0;
      const rates=[.94,.97,.92,.95,.91,.96];
      const pauses=[230,180,260,210,280,190];
      const speakNext=()=>{
        if(token!==voicePlaybackToken) return;
        if(segmentIndex>=segments.length){
          activeVoiceUtterances=[];
          updateVoiceAudioPanel(false,"재생이 끝났습니다. 가장 안전한 대응을 골라 보세요.");
          return;
        }
        const utterance=new SpeechSynthesisUtterance(segments[segmentIndex]);
        utterance.lang="ko-KR";
        utterance.rate=rates[segmentIndex%rates.length];
        const hasPreferredMaleVoice=!!(voice?.name && /Hyunsu|InJoon|BongJin|Male|남성/i.test(voice.name));
        utterance.pitch=hasPreferredMaleVoice ? 0.92 : 0.88;
        utterance.volume=1;
        if(voice) utterance.voice=voice;
        utterance.onstart=()=>{
          if(token===voicePlaybackToken) updateVoiceAudioPanel(true,"통화 속 압박과 고립 유도 표현을 주의 깊게 들어보세요.");
        };
        utterance.onend=()=>{
          if(token!==voicePlaybackToken) return;
          segmentIndex++;
          voicePauseTimer=setTimeout(speakNext,pauses[(segmentIndex-1)%pauses.length]);
        };
        utterance.onerror=event=>{
          if(token!==voicePlaybackToken) return;
          activeVoiceUtterances=[];
          updateVoiceAudioPanel(false,"음성을 재생하지 못했습니다. 다시 눌러 주세요.");
        };
        activeVoiceUtterances=[utterance];
        try { window.speechSynthesis.speak(utterance); }
        catch (_) { utterance.onerror({error:"synthesis-failed"}); }
      };
      updateVoiceAudioPanel(true,"음성을 준비하고 있습니다…");
      trackGameEvent("voice_play",{level_name:"voice_audio",fraud_type:s.type,question_number:state.index+1});
      speakNext();
    }

